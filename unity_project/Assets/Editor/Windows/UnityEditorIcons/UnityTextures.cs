    private class IconLightDarkComparer : IEqualityComparer<string>
    {
        public bool Equals(string x, string y)
        {
            return StripD(x).Equals(StripD(y));
        }

        public int GetHashCode(string obj) => StripD(obj).GetHashCode();

        private static string StripD(string str) => str.Strip("d_");
    }

    private void OnGUI()
    {
        EditorGUILayout.BeginHorizontal();
        EditorGUILayout.LabelField("Path", GUILayout.Width(PathWidth));
        EditorGUILayout.LabelField("Width", GUILayout.Width(TextureWidth));
        EditorGUILayout.LabelField("Height", GUILayout.Width(TextureHeight));
        EditorGUILayout.EndHorizontal();

        m_ScrollPos = GUILayout.BeginScrollView(m_ScrollPos, false, false);

        foreach (string path in m_IconNames)
        {
            if (string.IsNullOrEmpty(path) == false)
            {
                EditorGUILayout.BeginHorizontal();
                GUIItem(path);
                EditorGUILayout.EndHorizontal();
            }
        }

        GUILayout.EndScrollView();
    }

    private void GUIItem(string iconName)
    {
        string path = GetIconPath(iconName);
        var icon = LoadIcon(path);
        m_Content.image = icon;

        EditorGUILayout.TextField(path, GUILayout.Width(PathWidth));

        EditorGUILayout.LabelField(icon.width.ToString("N0"), GUILayout.Width(TextureWidth));
        EditorGUILayout.LabelField(icon.height.ToString("N0"), GUILayout.Width(TextureHeight));

        var height = GUILayout.Height((icon.height + 8).Min(256));
        var width = GUILayout.Width((icon.width + 16).Min(256));
        GUILayout.Button(m_Content, width, height);
    }

    private static string GetIconPath(string iconName)
    {
        return $"icons/{iconName}.png";
    }

    private static Texture2D LoadIcon(string iconPath)
    {
        return EditorGUIUtility.Load(iconPath) as Texture2D;
    }

